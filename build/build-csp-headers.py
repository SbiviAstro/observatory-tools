#!/usr/bin/env python3
"""
Regenerate the Content-Security-Policy script hashes in _headers.

Each calculator is one self-contained HTML file with its application inline.
Rather than allow inline script wholesale, the policy names the exact SHA-256
of each inline block. The browser runs a block only if its hash matches, so an
injected <script> is refused even though inline script is technically in use.

The catch is that a hash is only valid for the exact bytes it was taken from:
change one character of the application and the page stops running until the
hash is regenerated. Run this after any edit to a page, and before publishing.

    python3 build-csp-headers.py

Nothing is written unless every page parses and every hash is produced.
"""
import base64, hashlib, re, sys
from pathlib import Path

# Runs from build/ and writes into the published tree next door.
ROOT = Path(__file__).resolve().parent.parent / "public"

# Pages served with their own policy, because their inline script differs.
# The key is the file on disk; the value is the path it is published at. The
# policy has to name the published path, and the site links to stable names
# rather than versioned ones, so the two differ.
def calculators():
    out = []
    for name in ("dome-calculator.html", "ror-calculator.html"):
        f = ROOT / name
        if f.exists():
            out.append((f, "/" + name))
    return out

SIMPLE_PAGES = ["index.html", "about.html", "help.html", "overview.html",
                "horizon-guide.html", "dome-manual.html", "ror-manual.html",
                "license.html", "changelog.html", "disclaimer.html",
                "privacy.html", "faq.html", "404.html", "contact.html"]

BASE = """  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()"""


def inline_hashes(path: Path):
    """SHA-256 of every inline <script> block, in CSP source form."""
    html = path.read_text(encoding="utf-8")
    blocks = re.findall(r"<script(?![^>]*\bsrc=)[^>]*>(.*?)</script>", html, re.S)
    out = []
    for b in blocks:
        digest = hashlib.sha256(b.encode("utf-8")).digest()
        out.append("'sha256-" + base64.b64encode(digest).decode() + "'")
    return out


def policy(hashes, *, allow_form=False):
    script = " ".join(["'self'", "https://cdnjs.cloudflare.com", *hashes])
    parts = [
        "default-src 'self'",
        f"script-src {script}",
        # Inline style attributes are used throughout the markup. Style
        # injection cannot execute code, so this is a far smaller concern than
        # script and is left permissive deliberately.
        "style-src 'self' 'unsafe-inline'",
        "img-src 'self' data:",
        "font-src 'self' data:",
        "connect-src 'self' https://api.web3forms.com",
        "form-action 'self'" + (" https://api.web3forms.com" if allow_form else ""),
        "frame-ancestors 'none'",
        "base-uri 'self'",
        "object-src 'none'",
        "upgrade-insecure-requests",
    ]
    return "; ".join(parts)


def main():
    calcs = calculators()
    if not calcs:
        sys.exit("No calculator pages found in ../public - check the tree.")

    sections = []
    site_hashes = set()

    for page in SIMPLE_PAGES:
        p = ROOT / page
        if p.exists():
            site_hashes.update(inline_hashes(p))

    sections.append(
        "# Regenerated by build-csp-headers.py - do not hand-edit the hashes.\n"
        "# Re-run that script after changing any page, or the pages will not run.\n\n"
        "/*\n" + BASE + "\n  Content-Security-Policy: "
        + policy(sorted(site_hashes), allow_form=True) + "\n"
    )

    for src, served in calcs:
        h = inline_hashes(src)
        if not h:
            sys.exit(f"{src.name}: no inline script found - check the file is intact.")
        sections.append(
            f"{served}\n" + BASE + "\n  Content-Security-Policy: " + policy(h) + "\n"
        )

    (ROOT / "_headers").write_text("\n".join(sections), encoding="utf-8")
    print(f"_headers written: {len(site_hashes)} site hashes, "
          f"{len(calcs)} calculator policies")
    for src, served in calcs:
        print(f"   {src.name}  ->  {served}  ({len(inline_hashes(src))} inline block)")


if __name__ == "__main__":
    main()
